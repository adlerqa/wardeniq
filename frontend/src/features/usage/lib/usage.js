/**
 * Pure helpers for the LLM Usage & Cost screen (was the usage half of
 * compat/runtime/controllers/03-features-and-usage.js).
 */

export const fmtTok = (n) => Number(n || 0).toLocaleString();
export const fmtUsd = (c) => (c == null ? "—" : "$" + Number(c).toFixed(Number(c) < 1 ? 4 : 2));

/** The four KPI cards. */
export function statCards(t = {}) {
  return [
    { label: "Total tokens", value: fmtTok(t.total_tokens), type: "total", description: "All AI token usage" },
    { label: "Input tokens", value: fmtTok(t.prompt_tokens), type: "input", description: "Tokens sent to models" },
    { label: "Output tokens", value: fmtTok(t.completion_tokens), type: "output", description: "Tokens generated by models" },
    { label: "Estimated cost", value: fmtUsd(t.cost_usd), type: "cost", description: "Estimated provider spend" },
  ];
}

/** Models by total tokens, largest first: [[model, data]]. */
export const modelRows = (byModel = {}) => Object.entries(byModel).sort((a, b) => b[1].total_tokens - a[1].total_tokens);

export const projectLabel = (p) => p.name || p.project_id || "Unassigned";

/** Project filter: projects with usage, then every other project name (no duplicates). */
export function projectOptions(byProject, allNames) {
  const opts = byProject.map(projectLabel);
  const seen = new Set(opts);
  for (const n of allNames) {
    if (n && !seen.has(n)) {
      seen.add(n);
      opts.push(n);
    }
  }
  return opts;
}

/** Keep a filter's value only if it is still one of the options. */
export const keepValue = (value, options) => (value && options.includes(value) ? value : "");

export function recentRow(j) {
  return {
    process: j.label || j.type || "",
    project: j.project_name || j.project_id || "—",
    feature: j.feature_name || "—",
    status: j.status || "",
    statusClass: j.status === "failed" ? "err" : j.status === "running" ? "warn" : "ok",
    when: j.created_at ? new Date(j.created_at * 1000).toLocaleString() : "",
    models: Object.keys(j.by_model || {}).join(", ") || "—",
    tokens: fmtTok(j.total_tokens),
    cost: fmtUsd(j.cost_usd),
  };
}

/** A row's text as the filters match it (the cells' text, joined like textContent). */
export const recentText = (r) =>
  [r.process, r.project, r.feature, r.status, r.when, r.models, r.tokens, r.cost].join("");
export const modelText = ([m, d]) =>
  [m + (d.estimated ? " ~est" : ""), d.kind || "", fmtTok(d.calls), fmtTok(d.prompt_tokens), fmtTok(d.completion_tokens), fmtTok(d.total_tokens), fmtUsd(d.cost_usd)].join("");
export const projectText = (p) => [projectLabel(p), fmtTok(p.total_tokens), fmtUsd(p.cost_usd)].join("");

/** Row filter: case-insensitive substring of the row text; blank shows everything. */
export const rowShown = (text, q) => {
  const ql = (q || "").trim().toLowerCase();
  return !ql || text.toLowerCase().includes(ql);
};
